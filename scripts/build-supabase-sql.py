#!/usr/bin/env python3
"""Build the two paste-into-Supabase SQL files from the project sources.

  backend/scripts/supabase_sync_to_project.sql
      upgrades an EXISTING database in place (migrations + cleanup)
  backend/scripts/supabase_full_schema_from_scratch.sql
      creates a NEW database (schema.sql + migrations + cleanup)

Both end with the pre-flight check. Every CREATE POLICY is preceded by a
DROP POLICY IF EXISTS so the files are safe to run more than once.
Run from the repository root:  python3 scripts/build-supabase-sql.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "backend/src/main/resources"
OUT = ROOT / "backend/scripts"

MIGRATIONS = [
    "20261101_schema_migrations",
    "20261101_global_airport_directory",
    "20261101_role_access_rls",
    "20261102_landmark_catalog",
    "20261103_hotel_destination_catalog",
    "20261104_core_data_rls",
    "20261104_payment_attempts",
    "20261105_user_push_tokens",
    "20261107_user_notifications",
    "20261107_offer_flight_link",
    "20261115_user_saved_data",
]

FLYWAY_CLEANUP = """BEGIN;

-- flyway_schema_history is left over from an earlier tool; the project
-- tracks migrations in public.schema_migrations. Drop it only when it holds
-- nothing but the Flyway baseline row.
DO $$
BEGIN
    IF to_regclass('public.flyway_schema_history') IS NULL THEN
        RAISE NOTICE 'flyway_schema_history is already gone.';
    ELSIF EXISTS (SELECT 1 FROM public.flyway_schema_history
                  WHERE type <> 'BASELINE') THEN
        RAISE NOTICE 'Kept flyway_schema_history (it has real migration history).';
    ELSE
        EXECUTE 'DROP TABLE public.flyway_schema_history';
        RAISE NOTICE 'Dropped flyway_schema_history (baseline only).';
    END IF;
END
$$;

-- Laravel-era column that no backend code reads or writes.
ALTER TABLE public.users DROP COLUMN IF EXISTS remember_token;

COMMIT;
"""

SYNC_HEADER = """-- =====================================================================
-- Zentrip: bring an EXISTING Supabase database in line with the project
-- =====================================================================
-- Generated by scripts/build-supabase-sql.py - do not edit by hand.
-- Paste the WHOLE file into Supabase SQL Editor and press Run.
-- BEFORE RUNNING: take a backup (Database > Backups, or pg_dump).
--
-- Order (the project's migration files):
--   1. schema_migrations ledger          7. payment_attempts
--   2. airport directory columns         8. user_push_tokens
--   3. runtime role + RLS policies       9. user_notifications
--   4. landmark catalog tables          10. offers.flight_listing_id
--   5. hotel_destinations               11. favorites / price alerts / settings
--   6. core data RLS + visit lockdown   12. cleanup (flyway table, remember_token)
--
-- Every section is its own transaction and checks its prerequisites. If
-- one fails it is rolled back and the editor stops; earlier sections stay.
-- Fix the reported problem and run the whole file again: it is safe to
-- rerun. No customer rows are deleted.
-- =====================================================================
"""

SCRATCH_HEADER = """-- =====================================================================
-- Zentrip: COMPLETE database from scratch (new / empty Supabase project)
-- =====================================================================
-- Generated by scripts/build-supabase-sql.py - do not edit by hand.
-- Paste the WHOLE file into Supabase SQL Editor and press Run.
--
-- For a NEW, EMPTY project. For the existing production database use
-- supabase_sync_to_project.sql (it upgrades in place). Nothing here drops a
-- table that holds application data, and the file is safe to rerun.
--
--   PART 1  base schema: core tables, indexes, foreign keys, sample
--           airports and sample travel offers
--   PART 2  the 11 project migrations (ledger, runtime role and RLS,
--           landmark catalog, hotel destinations, payments, push tokens,
--           notifications, offer-flight link, favorites/alerts/settings)
--   PART 3  drop the unused users.remember_token column
--   PART 4  final check - every row must say OK
--
-- Result: 32 application tables + the schema_migrations ledger.
-- =====================================================================
"""


def rerunnable_policies(sql: str) -> str:
    lines = sql.split("\n")
    out = []
    for i, line in enumerate(lines):
        m = re.match(r"\s*CREATE POLICY\s+(\S+)", line)
        if m:
            on = re.search(r"\bON\s+([\w.]+)", line) or re.match(
                r"\s*ON\s+([\w.]+)", lines[i + 1])
            if not on:
                raise SystemExit(f"Cannot find table for policy: {line}")
            drop = f"DROP POLICY IF EXISTS {m.group(1)} ON {on.group(1)};"
            if not any(drop.lower() in prev.lower() for prev in out[-6:]):
                out.append(drop)
        out.append(line)
    return "\n".join(out)


def section(title: str, body: str) -> str:
    bar = "-- " + "-" * 69
    return f"\n{bar}\n-- {title}\n{bar}\n{body.rstrip()}\n"


def preflight() -> str:
    text = (OUT / "production_preflight.sql").read_text()
    start = text.index("WITH checks")
    end = text.index("ORDER BY sort_order;") + len("ORDER BY sort_order;")
    return text[start:end].replace(
        "'20261101_role_access_rls.sql (baseline - compare first, do not replay blindly)'",
        "'20261101_role_access_rls.sql'") + "\n"


def migrations() -> str:
    return "".join(
        section(f"{name}.sql",
                rerunnable_policies((RES / "migrations" / f"{name}.sql").read_text()))
        for name in MIGRATIONS)


def main() -> None:
    sync = (SYNC_HEADER + migrations()
            + section("Cleanup of objects the backend never uses", FLYWAY_CLEANUP)
            + section("Final check: every row should say OK", preflight()))
    (OUT / "supabase_sync_to_project.sql").write_text(sync)

    scratch = (SCRATCH_HEADER
               + section("PART 1: base schema (schema.sql)", (RES / "schema.sql").read_text())
               + "\n-- " + "=" * 69 + "\n-- PART 2: migrations\n-- " + "=" * 69 + "\n"
               + migrations()
               + section("PART 3: drop the unused Laravel-era column",
                         "ALTER TABLE public.users DROP COLUMN IF EXISTS remember_token;")
               + section("PART 4: final check - every row should say OK", preflight()))
    (OUT / "supabase_full_schema_from_scratch.sql").write_text(scratch)
    print("wrote", OUT / "supabase_sync_to_project.sql")
    print("wrote", OUT / "supabase_full_schema_from_scratch.sql")


if __name__ == "__main__":
    main()
