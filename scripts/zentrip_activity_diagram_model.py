"""Editable activity-diagram model for the verified Zentrip application flow."""

def _n(ident, label, kind="action", shape="box", branches=()):
    return {
        "id": ident,
        "label": label,
        "kind": kind,
        "shape": shape,
        "branches": list(branches),
    }


def _e(source, target, label="", kind="main"):
    return {"from": source, "to": target, "label": label, "kind": kind}


def _c(ident, label, role):
    return _n(ident, label, "connector", "connector", branches=()) | {
        "connector": label,
        "connector_role": role,
    }


